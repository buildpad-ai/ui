/**
 * AI chat config route — GET /api/ai-chat/config
 *
 * The settings `chocolateFactoryBackend` needs to call the Chocolate Factory agent
 * straight from the browser (read with `useChocolateFactoryConfig()`). Read from
 * the server's environment at request time, so changing them needs no rebuild.
 *
 * This hands the key to the browser on purpose: browser-direct is the only way
 * chat answers stream on Amplify Hosting, where API routes are buffered Lambdas.
 * Anyone who loads the page can read the key, so:
 *   - an agent key (`agk_…`, CHOCOLATE_FACTORY_AGENT_KEY) would reach only this
 *     agent, but Chocolate Factory's CORS headers don't allow its `x-agent-key`
 *     header from browsers yet: leave CHOCOLATE_FACTORY_AGENT_KEY unset here (when
 *     set, it is what this route returns, and every browser call would fail). Until
 *     then a browser call needs the project key (`cf_…`, CHOCOLATE_FACTORY_API_KEY),
 *     which reaches every agent in the project;
 *   - behind your app's auth, return 401 here for anonymous visitors.
 * To keep the key on the server instead, use `ai-chat-proxy-routes` and
 * `routeBackend()` (streams only on a long-lived Node server).
 *
 * Generated by @buildpad/cli
 */
import { NextResponse } from 'next/server';

export const dynamic = 'force-dynamic';

export async function GET() {
  const baseUrl = (process.env.CHOCOLATE_FACTORY_BASE_URL ?? '').trim();
  const apiKey = process.env.CHOCOLATE_FACTORY_AGENT_KEY || process.env.CHOCOLATE_FACTORY_API_KEY || '';
  const agentId = process.env.CHOCOLATE_FACTORY_AGENT_ID ?? '';

  if (!baseUrl || !apiKey || !agentId) {
    return NextResponse.json({ error: 'The assistant is not configured.' }, { status: 503 });
  }
  return NextResponse.json({ baseUrl, agentId, apiKey }, { headers: { 'Cache-Control': 'no-store' } });
}
