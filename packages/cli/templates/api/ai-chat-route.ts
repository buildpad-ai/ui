/**
 * AI chat proxy route — POST /api/ai-chat
 *
 * Streams one chat turn from the Chocolate Factory agent with the key added here,
 * so it never reaches the browser. Use with `routeBackend()` from the ai-chat
 * component. Chocolate Factory keeps the history (persisted mode): only the newest
 * turn is sent, with the conversation id recovered from the signed token.
 *
 * Streaming needs a long-lived Node server (self-hosted, a container, EC2). On
 * Amplify Hosting this route runs as a buffered Lambda (~30 s limit): answers
 * arrive all at once and long ones can time out. Use `chocolateFactoryBackend`
 * (browser-direct, /api/ai-chat/config) there instead.
 *
 * Body: { message: UIMessage, conversation?: string, vars?: Record<string, unknown> }
 *
 * Generated by @buildpad/cli
 */
import { NextRequest } from 'next/server';
import { AI_CHAT_CONVERSATION_HEADER } from '@/components/ui/ai-chat/backends';
import {
  authHeaders,
  chatOwner,
  chocolateFactorySettings,
  cleanVars,
  hasTokenSecret,
  MAX_MESSAGE_CHARS,
  plainResponse,
  setOwnerCookie,
  signConversation,
  userMessage,
  verifyConversation,
} from '@/lib/ai-chat/server';

export const runtime = 'nodejs';
export const dynamic = 'force-dynamic';
export const maxDuration = 300;

export async function POST(request: NextRequest) {
  // Behind your app's auth: reject anonymous requests here, and make chatOwner return the user's id.
  const settings = chocolateFactorySettings();
  if (!settings || !hasTokenSecret()) return plainResponse(503, 'The assistant is not configured.');

  let body: { message?: unknown; conversation?: unknown; vars?: unknown };
  try {
    body = await request.json();
  } catch {
    return plainResponse(400, 'Invalid request.');
  }

  const message = userMessage(body.message);
  if (!message) return plainResponse(400, `Send a question of up to ${MAX_MESSAGE_CHARS} characters, or up to 4 PNG, JPEG, WebP or GIF images.`);

  const { owner, isNew } = chatOwner(request);
  // A token that doesn't verify (another owner's, or tampered) starts a new conversation.
  const conversationId = body.conversation ? verifyConversation(owner, body.conversation) : null;
  const vars = cleanVars(body.vars);

  let upstream: Response;
  try {
    upstream = await fetch(`${settings.baseUrl}/api/agents/${encodeURIComponent(settings.agentId)}/run`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Accept: 'text/event-stream', ...authHeaders(settings.apiKey) },
      body: JSON.stringify({ message, ...(conversationId ? { conversationId } : {}), ...(vars ? { vars } : {}) }),
      // Stopping in the chat aborts this request, which cancels the agent run too.
      signal: request.signal,
      cache: 'no-store',
    });
  } catch (error) {
    if (request.signal.aborted) return new Response(null, { status: 499 });
    console.error('[ai-chat] Chocolate Factory request failed:', error);
    return plainResponse(502, "The assistant couldn't be reached. Try again in a moment.");
  }

  if (!upstream.ok || !upstream.body) {
    const detail = await upstream.text().catch(() => '');
    console.error(`[ai-chat] Chocolate Factory returned ${upstream.status}:`, detail.slice(0, 500));
    // 401/403/404 mean the app's agent settings are wrong, not anything the user did.
    const text = [401, 403, 404].includes(upstream.status)
      ? 'The assistant is misconfigured.'
      : 'The assistant ran into a problem answering that. Try again in a moment.';
    return plainResponse(upstream.status >= 500 ? 502 : upstream.status === 400 ? 400 : 503, text);
  }

  const headers: Record<string, string> = {
    'Content-Type': upstream.headers.get('Content-Type') ?? 'text/event-stream',
    'Cache-Control': 'no-cache, no-transform',
    'X-Accel-Buffering': 'no',
    'x-vercel-ai-ui-message-stream': 'v1',
  };
  // Chocolate Factory names the conversation on the first turn (and repeats it later).
  const newConversationId = upstream.headers.get('X-Conversation-Id');
  if (newConversationId) headers[AI_CHAT_CONVERSATION_HEADER] = signConversation(owner, newConversationId);

  const response = new Response(upstream.body, { status: 200, headers });
  if (isNew) setOwnerCookie(response, owner);
  return response;
}
