/**
 * Server helpers for the AI chat's proxy routes (app/api/ai-chat/route.ts and
 * app/api/ai-chat/history/route.ts): the Chocolate Factory settings, the signed
 * conversation tokens, and the checks on what the browser sends.
 *
 * Chocolate Factory keeps each conversation (persisted mode) and hands back its
 * whole history to anyone holding the id and the key. The routes hold the key, so
 * the browser only ever gets a token that binds the id to its owner:
 * `<conversationId>.<HMAC(AI_CHAT_SECRET, owner, id)>`. A token from another owner
 * starts a new conversation (chat) or is a 404 (history).
 *
 * The owner is a random id in an HttpOnly cookie, so this works without sign-in.
 * Behind your app's auth, return the signed-in user's id from `chatOwner` instead,
 * and reject anonymous requests in the routes.
 *
 * Generated by @buildpad/cli
 */
import { createHmac, randomUUID, timingSafeEqual } from 'crypto';
import type { NextRequest, NextResponse } from 'next/server';
import { parseImagePart, type ImagePart } from '@/components/ui/ai-chat/attachments';

export interface ChocolateFactorySettings {
  baseUrl: string;
  agentId: string;
  apiKey: string;
}

/** Longest question the routes accept (the chat's own limit). */
export const MAX_MESSAGE_CHARS = 8000;
const MAX_IMAGES = 4;
const OWNER_COOKIE = 'ai_chat_owner';
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * Settings from the environment, or null when the chat isn't configured.
 * CHOCOLATE_FACTORY_BASE_URL and CHOCOLATE_FACTORY_API_KEY come from the project's
 * Chocolate Factory connector; CHOCOLATE_FACTORY_AGENT_ID from the agent's page.
 */
export function chocolateFactorySettings(): ChocolateFactorySettings | null {
  const baseUrl = (process.env.CHOCOLATE_FACTORY_BASE_URL ?? '').trim().replace(/\/api\/agents(\/.*)?$/, '').replace(/\/+$/, '');
  const apiKey = process.env.CHOCOLATE_FACTORY_AGENT_KEY || process.env.CHOCOLATE_FACTORY_API_KEY || '';
  const agentId = process.env.CHOCOLATE_FACTORY_AGENT_ID ?? '';
  return baseUrl && apiKey && agentId ? { baseUrl, agentId, apiKey } : null;
}

export function authHeaders(apiKey: string): Record<string, string> {
  return apiKey.startsWith('agk_') ? { 'x-agent-key': apiKey } : { 'cf-api-key': apiKey };
}

export function plainResponse(status: number, message: string, headers?: Record<string, string>): Response {
  return new Response(message, { status, headers: { 'Content-Type': 'text/plain; charset=utf-8', ...headers } });
}

function secret(): string | null {
  const value = process.env.AI_CHAT_SECRET ?? '';
  return value.length >= 32 ? value : null;
}

/** Whether the token secret is set (32+ characters). The routes refuse to run without it. */
export function hasTokenSecret(): boolean {
  return secret() !== null;
}

/**
 * Who owns the conversations of this request: the HttpOnly cookie's random id, or
 * a new one (`isNew`, so the route sets the cookie). Replace with your signed-in
 * user's id when the app has auth.
 */
export function chatOwner(request: NextRequest): { owner: string; isNew: boolean } {
  const existing = request.cookies.get(OWNER_COOKIE)?.value;
  if (existing && UUID.test(existing)) return { owner: existing, isNew: false };
  return { owner: randomUUID(), isNew: true };
}

export function setOwnerCookie(response: NextResponse | Response, owner: string) {
  const cookie = `${OWNER_COOKIE}=${owner}; Path=/api/ai-chat; HttpOnly; SameSite=Lax; Max-Age=31536000${process.env.NODE_ENV === 'production' ? '; Secure' : ''}`;
  response.headers.append('Set-Cookie', cookie);
}

function signature(owner: string, conversationId: string): string {
  return createHmac('sha256', secret()!).update(`ai-chat:${owner}:${conversationId.toLowerCase()}`).digest('base64url');
}

export function signConversation(owner: string, conversationId: string): string {
  return `${conversationId}.${signature(owner, conversationId)}`;
}

/** The conversation id when the token was issued to this owner, otherwise null. */
export function verifyConversation(owner: string, token: unknown): string | null {
  if (typeof token !== 'string' || token.length > 200 || !secret()) return null;
  const dot = token.indexOf('.');
  if (dot < 0) return null;
  const conversationId = token.slice(0, dot);
  if (!UUID.test(conversationId)) return null;
  const given = Buffer.from(token.slice(dot + 1));
  const expected = Buffer.from(signature(owner, conversationId));
  return given.length === expected.length && timingSafeEqual(given, expected) ? conversationId : null;
}

type UserPart = { type: 'text'; text: string } | ImagePart;

/** The user's turn reduced to text and checked images, or null when there is nothing (valid) to send. */
export function userMessage(input: unknown): { id?: string; role: 'user'; parts: UserPart[] } | null {
  if (!input || typeof input !== 'object') return null;
  const { id, role, parts } = input as { id?: unknown; role?: unknown; parts?: unknown };
  if (role !== 'user' || !Array.isArray(parts)) return null;

  const texts = parts
    .filter((part): part is { type: 'text'; text: string } => part?.type === 'text' && typeof part.text === 'string')
    .map((part) => ({ type: 'text' as const, text: part.text }));
  const fileParts = parts.filter((part) => part?.type === 'file');
  const images = fileParts.map(parseImagePart);
  if (images.some((image) => image === null) || images.length > MAX_IMAGES) return null;
  const length = texts.reduce((sum, part) => sum + part.text.length, 0);
  if (length > MAX_MESSAGE_CHARS || (!texts.some((part) => part.text.trim()) && images.length === 0)) return null;

  return { ...(typeof id === 'string' ? { id: id.slice(0, 100) } : {}), role: 'user', parts: [...texts, ...(images as ImagePart[])] };
}

/** Template variables from the browser: a plain object of strings, numbers and booleans, bounded in size. */
export function cleanVars(input: unknown): Record<string, string | number | boolean> | undefined {
  if (!input || typeof input !== 'object' || Array.isArray(input)) return undefined;
  const vars: Record<string, string | number | boolean> = {};
  for (const [key, value] of Object.entries(input).slice(0, 30)) {
    if (!/^[A-Za-z_][A-Za-z0-9_]{0,63}$/.test(key)) continue;
    if (typeof value === 'string') vars[key] = value.slice(0, 2000);
    else if (typeof value === 'number' || typeof value === 'boolean') vars[key] = value;
  }
  return Object.keys(vars).length ? vars : undefined;
}
