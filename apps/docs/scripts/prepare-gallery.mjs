/**
 * Prepares the styleguide's live component gallery. Run before `next dev` /
 * `next build`; every output is gitignored so it always matches the installed
 * Mantine, the shipped templates and the demo modules.
 *
 * 1. app-globals.scoped.css — a gallery-scoped copy of the shipped
 *    packages/cli/templates/app/globals.css. Its variant-contrast overrides
 *    and body styles target `:root[data-mantine-color-scheme=…]` and `body`,
 *    which would restyle the whole docs site and could not follow the
 *    Showcase's own light/dark toggle; only those selectors are rewritten to
 *    the gallery root, so the gallery gets the exact shipped rules.
 *
 * 2. mantine-styles.ts — imports for every @mantine/core stylesheet except
 *    baseline.css (its html/body resets would restyle the docs chrome), in
 *    the order @mantine/core/styles.css concatenates them. Order matters:
 *    UnstyledButton's reset must come before Button, Input before the
 *    inputs, and so on.
 *
 * 3. lazy/<sections|templates>/<module>.tsx — a next/dynamic wrapper for
 *    every exported demo. Every MDX page renders through the one Nextra
 *    catch-all route, so demos imported statically would put the whole
 *    gallery (Mantine, tiptap, dates, sample data) in the bundle of every
 *    docs page. MDX imports demos from these wrappers instead, and each
 *    module loads only on the pages that render it. The wrappers import the
 *    module's stylesheets (and gallery/styles.ts) statically, so pages still
 *    link the CSS in their HTML: gallery CSS is in every docs page's CSS,
 *    but it is hashed or scoped to .bp-gallery.
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const galleryDir = resolve(here, '../components/styleguide/gallery');
const ROOT = '.bp-gallery';
const BANNER = (source) =>
  `GENERATED by apps/docs/scripts/prepare-gallery.mjs from ${source} — do not edit.`;

// ── 1. Scoped app globals ────────────────────────────────────────────────
const globalsPath = resolve(here, '../../../packages/cli/templates/app/globals.css');
const scoped = readFileSync(globalsPath, 'utf8')
  // Fonts are loaded once by the Showcase.
  .replace(/^@import url\([^)]*\);\s*$/m, '')
  .replace(/:root\[data-mantine-color-scheme=/g, `${ROOT}[data-mantine-color-scheme=`)
  .replace(/^body\s*\{/m, `${ROOT} {`);

if (/(^|[\s,]):root\b/.test(scoped) || /^body\s*\{/m.test(scoped)) {
  throw new Error('prepare-gallery: globals.css has a :root/body selector this script does not rewrite');
}

writeFileSync(
  join(galleryDir, 'app-globals.scoped.css'),
  `/* ${BANNER('packages/cli/templates/app/globals.css')} */\n${scoped}`,
);

// ── 2. Ordered Mantine stylesheet imports ────────────────────────────────
const require = createRequire(join(galleryDir, 'Gallery.tsx'));
// styles.css is an exported subpath (package.json is not), so anchor on it.
const bundlePath = require.resolve('@mantine/core/styles.css');
const bundle = readFileSync(bundlePath, 'utf8');
const stylesDir = join(dirname(bundlePath), 'styles');

const position = (file) => {
  const css = readFileSync(join(stylesDir, file), 'utf8');
  // Component files are keyed by their hashed classes (.m_1b7284a3); the
  // earliest one in the bundle marks where the file was concatenated.
  const hashes = [...new Set(css.match(/\.m_[0-9a-f]{8}/g) ?? [])];
  const found = (hashes.length ? hashes : [css.trim().slice(0, 80)])
    .map((needle) => bundle.indexOf(needle))
    .filter((index) => index >= 0);
  if (!found.length) throw new Error(`prepare-gallery: cannot place ${file} in styles.css`);
  return Math.min(...found);
};

const files = readdirSync(stylesDir)
  .filter((f) => f.endsWith('.css') && !f.endsWith('.layer.css') && f !== 'baseline.css')
  .map((f) => [f, position(f)])
  .sort((a, b) => a[1] - b[1])
  .map(([f]) => `import '@mantine/core/styles/${f}';`);

writeFileSync(
  join(galleryDir, 'mantine-styles.ts'),
  `// ${BANNER('@mantine/core/styles.css')}\n${files.join('\n')}\n`,
);

// ── 3. Lazy demo wrappers ────────────────────────────────────────────────
const lazyDir = join(galleryDir, 'lazy');
rmSync(lazyDir, { recursive: true, force: true });
let demoCount = 0;
for (const group of ['sections', 'templates']) {
  mkdirSync(join(lazyDir, group), { recursive: true });
  for (const file of readdirSync(join(galleryDir, group)).filter((f) => f.endsWith('.tsx'))) {
    const module = file.replace(/\.tsx$/, '');
    const source = readFileSync(join(galleryDir, group, file), 'utf8');
    const demos = [...source.matchAll(/^export function ([A-Z]\w*)/gm)].map((m) => m[1]);
    if (!demos.length) continue;
    demoCount += demos.length;
    const stylesheets = [...source.matchAll(/^import (?:\w+ from )?'([^']+\.css)';/gm)].map((m) =>
      m[1].startsWith('./') ? `../../${group}/${m[1].slice(2)}` : m[1],
    );
    const lines = [
      `// ${BANNER(`gallery/${group}/${file}`)}`,
      `'use client';`,
      '',
      `import dynamic from 'next/dynamic';`,
      `import '../../styles';`,
      ...stylesheets.map((path) => `import '${path}';`),
      '',
      `const load = () => import('../../${group}/${module}');`,
      '',
      ...demos.map((name) => `export const ${name} = dynamic(() => load().then((m) => m.${name}));`),
    ];
    writeFileSync(join(lazyDir, group, `${module}.tsx`), `${lines.join('\n')}\n`);
  }
}

console.log(`prepare-gallery: wrote scoped globals, ${files.length} Mantine imports, ${demoCount} lazy demos`);
